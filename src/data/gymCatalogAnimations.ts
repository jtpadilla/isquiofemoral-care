type Options = Omit<Spec, 'scene' | 'basePose' | 'durations' | 'poses' | 'activations' | 'peaks'>;
type Rhythm = Pick<Spec, 'durations' | 'poses' | 'activations' | 'peaks'>;

const add = (name: string, scene: ExerciseScene, basePose: Partial<Pose>, rhythm: Rhythm, options: Options, source?: PoseKey, peakOnly?: boolean) => {
  const sources = source ? [{ source, peakOnly }] : [];
  return [name, build(name, { scene, basePose, ...rhythm, ...options, sources })] as [string, ExerciseAnimation];
};

